"""Build the offline stock directory from nasdaqlisted.txt and SPY / DIA holdings XLSX files."""
import csv
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile


def fund_holdings(path):
    with ZipFile(path) as book:
        strings = [''.join(row.itertext()) for row in ET.fromstring(book.read('xl/sharedStrings.xml'))]
        rows = ET.fromstring(book.read('xl/worksheets/sheet1.xml')).findall('.//{*}row')
        for row in rows:
            cells = {}
            for cell in row.findall('{*}c'):
                value = cell.findtext('{*}v', '')
                cells[re.sub(r'\d', '', cell.get('r'))] = strings[int(value)] if cell.get('t') == 's' else value
            symbol = cells.get('B', '')
            if cells.get('H') == 'USD' and re.fullmatch(r'[A-Z]+(?:\.[AB])?', symbol):
                yield symbol, cells['A'].replace('/THE', '').replace(' + ', ' & ').strip().title()


def build(nasdaq, spy, dia):
    stocks = {}
    with open(nasdaq, encoding='utf-8-sig') as directory:
        for row in csv.DictReader(directory, delimiter='|'):
            if row['Test Issue'] != 'N' or row['ETF'] != 'N':
                continue
            name, _, security = row['Security Name'].rpartition(' - ')
            if not name or re.search(r'preferred|warrant|notes? due|debentur|rights? to|closed.end fund', security, re.I):
                continue
            if re.search(r'shares?|stock|deposit[ao]ry|\bADSs?\b|limited partnership interest', security, re.I):
                stocks[row['Symbol']] = [name.strip(), 1]
    for path, flag in [(spy, 2), (dia, 4)]:
        for symbol, name in fund_holdings(path):
            stocks.setdefault(symbol, [name, 0])[1] |= flag
    if len(stocks) < 2500 or sum(bool(flags & 4) for _, flags in stocks.values()) != 30:
        raise ValueError('Incomplete market directory')
    return stocks


if __name__ == '__main__':
    stocks = build(*sys.argv[1:])
    destination = Path(__file__).resolve().parents[1] / 'dist' / 'market-catalog.js'
    with destination.open('w') as output:
        output.write('// Generated by scripts/build-market-catalog.py. Flags: Nasdaq listings 1, SPY equities 2, DIA equities 4.\nexport const MARKET_CATALOG = [\n')
        for symbol, (name, flags) in sorted(stocks.items()):
            output.write('  ' + json.dumps([symbol, name, flags], ensure_ascii=False) + ',\n')
        output.write('];\n')
