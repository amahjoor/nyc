def digest(path):
    with Path(path).open("rb") as handle:
        return hashlib.file_digest(handle, "sha256").hexdigest()


def discover_paint(rgb, pavement, source_ids):
    """Conservative thin, bright components; no extension through occlusions."""
    import numpy as np
    from scipy import ndimage as ndi
    pixels = rgb.astype(float)
    luminance = pixels.mean(2)
    chroma = pixels.max(2) - pixels.min(2)
    inside = ndi.distance_transform_edt(pavement) > 5
    candidates = ((luminance - ndi.uniform_filter(luminance, size=13) > 17)
                  & (luminance > 153) & (chroma < 42) & inside)
    labels, _ = ndi.label(candidates)
    records = []
    for label, slices in enumerate(ndi.find_objects(labels), 1):
        if slices is None:
            continue
        ys, xs = np.where(labels[slices] == label)
        ys, xs = ys + slices[0].start, xs + slices[1].start
        if not 12 <= len(xs) <= 500:
            continue
        coords = np.stack((xs, ys), axis=1)
        _, axes = np.linalg.eigh(np.cov(coords.T))
        along, across = coords @ axes[:, 1], coords @ axes[:, 0]
        length, width = float(np.ptp(along) + 1), float(np.ptp(across) + 1)
        if not 8 <= length <= 130 or width > 4.4 or length / width < 4.5:
            continue
        identities = source_ids[ys, xs]
        records.append({"id": len(records), "box": [int(xs.min()), int(ys.min()),
                        int(xs.max() + 1), int(ys.max() + 1)], "pixels": len(xs),
                        "length": round(length, 1), "width": round(width, 1),
                        "sourceIndex": int(np.bincount(identities[identities >= 0]).argmax()),
                        "coords": coords.tolist()})
    return records


def candidates_digest(records):
    # Explicit canonical serialization prevents an algorithm change from quietly
    # reusing old review decisions with new component numbers.
    return hashlib.sha256(json.dumps(records, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def review_paint(records, image_hash):
    if image_hash != REVIEWED_IMAGE_SHA256 or candidates_digest(records) != REVIEWED_CANDIDATES_SHA256:
        raise ValueError("Image/candidate hash changed; regenerate and visually review paint candidates first")
    return [record for record in records if record["id"] not in PAINT_REJECTED]


def pavement_masks(features, size, grid):
    import numpy as np
    masks, ids = {}, np.full((size[1], size[0]), -1, dtype=np.int16)
    for index, feature in enumerate(features):
        # The source's 350020 records are shoulder/median geometry, not ordinary
        # lane pavement. Preserve their existing appearance, even if gray.
        if str(feature["properties"].get("sourceSubcode")) == "350020":
            continue
        mask = source.polygons_to_mask(feature["geometry"], size, grid)
        masks[index] = mask
        ids[mask] = index
    return masks, ids


def clean_sample(rgb, mask, exclusion):
    """Robust unshadowed pavement sample, not a claim to recover true albedo."""
    import numpy as np
    from scipy import ndimage as ndi
    pixels = rgb.astype(float)
    light = pixels.mean(2)
    chroma = np.ptp(pixels, axis=2)
    interior = ndi.distance_transform_edt(mask) > 4
    if int(interior.sum()) < 32:
        return None
    low, high = np.percentile(light[interior], [30, 75])
    # High contrast captures paint/vehicle boundaries. Percentile trimming also
    # removes dark cast shadows and bright bodies not among the SAM prompts.
    local_contrast = np.abs(light - ndi.uniform_filter(light, size=11))
    clean = interior & ~exclusion & (light >= low) & (light <= high) & (chroma < 32) & (local_contrast < 5)
    if int(clean.sum()) < 32:
        return None
    color = np.rint(np.median(rgb[clean], axis=0)).astype(int).tolist()
    ys, xs = np.where(clean)
    return {"color": "#" + "".join(f"{value:02x}" for value in color),
            "cleanPixels": int(clean.sum()), "excludedPixels": int(mask.sum() - clean.sum()),
            "pixelBox": [int(xs.min()), int(ys.min()), int(xs.max() + 1), int(ys.max() + 1)],
            "luminancePercentiles": [round(float(low), 2), round(float(high), 2)]}, clean


def segment_occluders(image, output, model_directory, device):
    import numpy as np
    from scipy import ndimage as ndi
    import torch
    import transformers
    from transformers import SamModel, SamProcessor
    from PIL import Image
    weights = model_directory / "model.safetensors"
    if digest(weights) != source.WEIGHTS_SHA256:
        raise ValueError("SAM weights do not match the pinned revision")
    processor = SamProcessor.from_pretrained(str(model_directory))
    model = SamModel.from_pretrained(str(model_directory), use_safetensors=True).to(device).eval()
    exclusion = np.zeros((image.height, image.width), bool)
    records = []
    for group_index, group in enumerate(VEHICLE_GROUPS):
        left, top, right, bottom = group["crop"]
        crop = image.crop(group["crop"])
        input_image = processor(crop, return_tensors="pt").to(device)
        with torch.inference_mode():
            embedding = model.get_image_embeddings(input_image["pixel_values"])
        for box in group["boxes"]:
            local = [box[0] - left, box[1] - top, box[2] - left, box[3] - top]
            point = [(local[0] + local[2]) / 2, (local[1] + local[3]) / 2]
            inputs = processor(crop, input_points=[[point]], input_labels=[[1]],
                               input_boxes=[[local]], return_tensors="pt").to(device, dtype=torch.float32)
            inputs.pop("pixel_values")
            with torch.inference_mode():
                result = model(image_embeddings=embedding, **inputs)
            masks = processor.image_processor.post_process_masks(result.pred_masks.cpu(),
                       inputs["original_sizes"].cpu(), inputs["reshaped_input_sizes"].cpu())[0][0].numpy()
            scores = result.iou_scores[0, 0].cpu().numpy()
            best = int(np.argmax(scores))
            mask = masks[best].astype(bool)
            box_mask = np.zeros_like(mask)
            box_mask[local[1]:local[3], local[0]:local[2]] = True
            containment = int((mask & box_mask).sum()) / max(1, int(mask.sum()))
            # These are occluder-specific gates, not replacements for the old
            # whole-road source-agreement gates. Failed masks remain evidence.
            accepted = float(scores[best]) >= .75 and containment >= .90 and 20 <= int(mask.sum()) <= 1800
            identity = f"vehicle-{len(records):02d}"
            Image.fromarray(mask.astype("uint8") * 255).save(output / f"{identity}.png")
            if accepted:
                exclusion[top:bottom, left:right] |= ndi.binary_dilation(mask, iterations=2)
            records.append({"id": identity, "class": "vehicle", "classSource": "visual source-image inspection",
                            "crop": group["crop"], "box": box, "point": [point[0] + left, point[1] + top],
                            "predictedIou": float(scores[best]), "boxContainment": containment,
                            "candidatePixels": int(mask.sum()), "accepted": accepted,
                            "use": "exclude from appearance sampling only",
                            "mask": f"./road-pilot-vision/{identity}.png"})
            print(json.dumps({"id": identity, "accepted": accepted, "predictedIou": float(scores[best])}), flush=True)
    return exclusion, records, {"id": source.MODEL, "revision": source.REVISION,
            "weightsSha256": source.WEIGHTS_SHA256, "license": "Apache-2.0", "device": device,
            "torch": torch.__version__, "transformers": transformers.__version__, "weightsBundled": False}


def mask_polygons(coords, reference_geometry, grid, size):
    import numpy as np
    mask = np.zeros((size[1], size[0]), bool)
    for x, y in coords:
        mask[y, x] = True
    # Use source pixel geometry without a fitted/full-length lane reconstruction.
    # Consequently broken/occluded paint stays broken and no guessed stripe is added.
    from rasterio.features import shapes
    from shapely.geometry import shape
    from shapely import transform, union_all
    pieces = [shape(geometry) for geometry, value in shapes(mask.astype("uint8"), mask=mask) if value]
    geometry = union_all(pieces).simplify(.20, preserve_topology=True)
    geometry = transform(geometry, lambda points: np.asarray([source.pixel_to_lonlat(x, y, grid) for x, y in points]))
    geometry = geometry.intersection(shape(reference_geometry))
    geometry = transform(geometry, lambda points: np.asarray([source.ortho.project(lon, lat) for lon, lat in points]))
    parts = [geometry] if geometry.geom_type == "Polygon" else list(geometry.geoms)
    return [{"outer": [[round(x, 4), round(z, 4)] for x, z in polygon.exterior.coords],
             "holes": [[[round(x, 4), round(z, 4)] for x, z in ring.coords] for ring in polygon.interiors]}
            for polygon in parts if polygon.geom_type == "Polygon" and polygon.area > .02]


def review_sheet(image, candidates, output):
    from PIL import Image, ImageDraw
    sheet = Image.new("RGB", (1000, 140 * math.ceil(len(candidates) / 10)), (25, 25, 25))
    draw = ImageDraw.Draw(sheet)
    for index, record in enumerate(candidates):
        x0, y0, x1, y1 = record["box"]
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        crop = image.crop((cx - 15, cy - 25, cx + 15, cy + 25)).resize((90, 120))
        pen = ImageDraw.Draw(crop)
        pen.rectangle(((x0 - cx + 15) * 3, (y0 - cy + 25) * 2.4,
                       (x1 - cx + 15) * 3, (y1 - cy + 25) * 2.4), outline="orange", width=1)
        x, y = index % 10 * 100, index // 10 * 140
        sheet.paste(crop, (x, y + 20))
        label = "visual no" if record["id"] in PAINT_REJECTED else "visual yes"
        draw.text((x, y), f"{record['id']} {label}", fill="white")
    sheet.save(output / "paint-review.jpg", quality=94)


def occluder_sheet(image, records, output):
    """Source and model output side by side, including failed proposals."""
    import numpy as np
    from PIL import Image, ImageDraw
    sheet = Image.new("RGB", (1040, 170 * math.ceil(len(records) / 4)), (25, 25, 25))
    draw = ImageDraw.Draw(sheet)
    for index, record in enumerate(records):
        x0, y0, x1, y1 = record["box"]
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        box = [cx - 30, cy - 35, cx + 30, cy + 35]
        part = image.crop(box)
        mask = Image.open(output / (record["id"] + ".png"))
        crop_x, crop_y = record["crop"][:2]
        selected = np.asarray(mask.crop([box[0] - crop_x, box[1] - crop_y,
                                        box[2] - crop_x, box[3] - crop_y])) > 0
        overlay = np.asarray(part).copy()
        color = np.array([40, 220, 100] if record["accepted"] else [240, 80, 50])
        overlay[selected] = (.45 * overlay[selected] + .55 * color).astype("uint8")
        x, y = index % 4 * 260, index // 4 * 170
        sheet.paste(part.resize((120, 140)), (x, y + 25))
        sheet.paste(Image.fromarray(overlay).resize((120, 140)), (x + 125, y + 25))
        decision = "accepted" if record["accepted"] else "rejected"
        draw.text((x, y), f"{record['id']} {decision} {record['predictedIou']:.3f}", fill="white")
    sheet.save(output / "vehicle-review.jpg", quality=94)


def run(args):
    import numpy as np
    import torch
    from PIL import Image, ImageDraw
    image_path = ROOT / "dist/road-reconstruction/aerial.png"
    reference_path = ROOT / "dist/road-reconstruction/reference.geojson"
    report = json.loads((ROOT / "dist/road-reconstruction-review.json").read_text())
    image = Image.open(image_path).convert("RGB")
    rgb = np.asarray(image)
    grid = report["imagery"]["grid"]
    features = json.loads(reference_path.read_text())["features"]
    output = args.output.parent / "road-pilot-vision"
    output.mkdir(parents=True, exist_ok=True)
    masks, ids = pavement_masks(features, image.size, grid)
    candidates = discover_paint(rgb, ids >= 0, ids)
    review_sheet(image, candidates, output)
    (output / "paint-candidates.json").write_text(json.dumps(candidates, separators=(",", ":")) + "\n")
    accepted_paint = review_paint(candidates, digest(image_path))
    device = args.device or ("mps" if torch.backends.mps.is_available() else "cpu")
    exclusion, occluders, model = segment_occluders(image, output, args.model_directory, device)
    occluder_sheet(image, occluders, output)
    Image.fromarray(exclusion.astype("uint8") * 255).save(output / "vehicle-exclusion.png")
    clean_mask = np.zeros(ids.shape, bool)
    surfaces = []
    for index, mask in masks.items():
        sample = clean_sample(rgb, mask, exclusion)
        if sample is None:
            continue
        metadata, clean = sample
        clean_mask |= clean
        properties = features[index]["properties"]
        surfaces.append({"sourceFeatureId": properties["sourceFeatureId"], "kind": properties["kind"],
                         "color": metadata.pop("color"), "roughness": .94, "colorVariation": .015,
                         "sourceSample": metadata, "sourceUrl": properties["sourceUrl"],
                         "reviewStatus": "accepted", "use": "appearance only; measured geometry unchanged"})
    Image.fromarray(clean_mask.astype("uint8") * 255).save(output / "pavement-samples.png")
    markings = []
    for record in accepted_paint:
        coords = np.asarray(record["coords"])
        if exclusion[coords[:, 1], coords[:, 0]].any():
            continue
        feature = features[record["sourceIndex"]]
        polygons = mask_polygons(record["coords"], feature["geometry"], grid, image.size)
        if not polygons:
            continue
        color = np.rint(np.median(rgb[coords[:, 1], coords[:, 0]], axis=0)).astype(int)
        markings.append({"id": f"paint-{record['id']:03d}", "sourceFeatureId": feature["properties"]["sourceFeatureId"],
                         "color": "#" + "".join(f"{value:02x}" for value in color), "polygons": polygons,
                         "reviewStatus": "accepted", "evidence": {
                            "candidateId": record["id"], "pixelBox": record["box"], "pixelCount": record["pixels"],
                            "method": "classical local-contrast component; visually checked source crop",
                            "reviewMethod": "assistant visual inspection of source image and highlighted contact sheet",
                            "predictedIou": None, "pixelCoordinates": record["coords"]}})
    overlay = np.array(image)
    overlay[clean_mask] = (.75 * overlay[clean_mask] + .25 * np.array([20, 210, 80])).astype("uint8")
    overlay[exclusion] = [230, 70, 80]
    for marking in markings:
        for x, y in marking["evidence"]["pixelCoordinates"]:
            overlay[y, x] = [0, 225, 255]
    Image.fromarray(overlay).save(output / "review-overlay.jpg", quality=93)
    min_x, min_z = source.ortho.project(*source.pixel_to_lonlat(0, 0, grid))
    max_x, max_z = source.ortho.project(*source.pixel_to_lonlat(image.width, image.height, grid))
    result = {"version": 1, "id": "meadow-lake-pavement-appearance", "origin": source.ortho.ORIGIN,
              "bounds": {"minX": min_x, "maxX": max_x, "minZ": min_z, "maxZ": max_z},
              "method": "SAM-assisted vehicle exclusion, robust image-color sampling, and visually reviewed classical paint extraction",
              "model": model, "imagery": {**{key: report["imagery"][key] for key in ["source", "year", "license", "grid", "captureDates"]},
                    "url": "./road-reconstruction/aerial.png", "sha256": digest(image_path),
                    "width": image.width, "height": image.height},
              "reference": {"url": "./road-reconstruction/reference.geojson", "sha256": digest(reference_path)},
              "review": {"imageSha256": REVIEWED_IMAGE_SHA256, "candidatesSha256": REVIEWED_CANDIDATES_SHA256,
                         "candidatesFileSha256": digest(output / "paint-candidates.json"),
                         "contactSheet": "./road-pilot-vision/paint-review.jpg", "overlay": "./road-pilot-vision/review-overlay.jpg",
                         "rejectedCandidateIds": sorted(PAINT_REJECTED), "method": "visual source crop inspection; not an independent accuracy benchmark"},
              "surfaces": surfaces, "markings": markings, "occluders": occluders,
              "summary": {"surfaceMaterials": len(surfaces), "paintCandidates": len(candidates), "paintAccepted": len(markings),
                          "vehicleCandidates": len(occluders), "vehicleMasksAccepted": sum(record["accepted"] for record in occluders),
                          "materialSamplePixels": int(clean_mask.sum()), "vehicleExcludedPixels": int(exclusion.sum())},
              "limitations": ["Bounded Meadow Lake pilot, not citywide automated reconstruction.",
                    "SAM refines manually identified vehicles, not paint or road semantics; its score is not class confidence.",
                    "No reviewed parking-stall paint was found; cones, stains and parked vehicles are not reproduced as markings.",
                    "Source paint vectorization is conservative and incomplete; occluded, faint and rejected features are omitted.",
                    "Shadow rejection uses brightness/contrast trimming, not a verified shadow-class model; vehicle masks cover reviewed examples only.",
                    "Median photo color is an appearance estimate, not calibrated albedo; roughness and fine variation are rendering approximations.",
                    "No objects are inpainted into photos; a source-colored material replaces the photo on survey-backed surfaces.",
                    "Existing whole-road SAM proposals remain rejected; this stage changes none of their thresholds."]}
    args.output.write_text(json.dumps(result, separators=(",", ":")) + "\n")
    print(json.dumps(result["summary"]), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-directory", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "dist/road-pilot-appearance.json")
    parser.add_argument("--device", choices=["mps", "cpu", "cuda"])
    run(parser.parse_args())


if __name__ == "__main__":
    main()
