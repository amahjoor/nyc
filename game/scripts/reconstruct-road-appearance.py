"""Build a bounded, reviewed pavement appearance pilot from NYC's 2024 imagery.

Run with the existing isolated reconstruction environment:
  python scripts/reconstruct-road-appearance.py --model-directory /tmp/nyc-reconstruction-ai-model

SAM refines visually identified vehicle boxes, not semantic road/paint labels.
Classical image contrast proposes paint; an image-hash-locked visual review
allows only observed paint through. Surveyed footprints and heights never come
from this stage. The unaccepted whole-road SAM trial is left unchanged.
"""

