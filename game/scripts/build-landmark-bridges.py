"""Bundle measured decks for the principal crossings outside the existing street tiles."""
import json
from pathlib import Path
import runpy
from urllib.parse import urlencode
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
street = runpy.run_path(str(ROOT / 'scripts/import-street-detail.py'))
names = {
    'kosciuszko': 'Kosciuszko Bridge',
    'rfk': 'ROBERT F KENNEDY BRG',
    'williamsburg': 'Williamsburg Bridge',
    'queensboro': 'ED KOCH QUEENSBORO BRIDGE',
    'whitestone': 'BRONX-WHITESTONE BRIDGE',
    'throgs-neck': 'THROGS NECK BRIDGE',
    'verrazzano': 'Verrazano-Narrows Bridge',
}
layer = street['ARCGIS_ROOT'] + street['LAYERS']['transport']['dataset']
directory = ROOT / 'dist/landmark-bridges'
directory.mkdir(exist_ok=True)
index = []
for key, name in names.items():
    query = urlencode(dict(where=f"NAME='{name}' AND SUB_FEATURE_CODE=230000", outFields='*',
                           returnZ='true', outSR=4326, f='geojson', orderByFields='OBJECTID'))
    with urlopen(layer + '/query?' + query, timeout=45) as response:
        rows = street['normalize_response']('transport', json.load(response))
    features = street['convert_rows']('transport', rows, dict(minX=-40000, maxX=40000, minZ=-40000, maxZ=40000))
    decks = [f for f in features if f['elevationStatus'] == 'surveyed']
    if not features:
        raise ValueError(f'Missing source footprint for {name}')
    if not decks:
        print(name, 'has unresolved outline elevations')
        continue
    bounds = street['bounds_of']([p for deck in decks for p in deck['polygon']])
    street['compact_write'](directory / f'{key}.json', dict(structures=decks, surfaces=[]))
    index.append(dict(key=f'bridge:{key}', bounds=bounds, url=f'./landmark-bridges/{key}.json'))
    print(name, len(decks), 'measured components')
(ROOT / 'dist/landmark-bridges.js').write_text('// Generated by scripts/build-landmark-bridges.py from NYC OTI transport outlines.\n'
    + 'export const landmarkBridges = ' + json.dumps(index, separators=(',', ':')) + ';\n')
