"""Build the NYC sailing area from DCP borough waters and adjoining Census estuary polygons.

Requires Shapely 2 and pyshp. The detailed dry shoreline is already in boroughs.json.
"""
import json
import math
import io
import zipfile
import shapefile
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

from shapely.geometry import shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1] / "dist"
SOURCE = "https://services5.arcgis.com/GfwWNkhOj9bNBqoJ/arcgis/rest/services/NYC_Borough_Boundary_Water_Included/FeatureServer/0"
query = urlencode({"where": "1=1", "outFields": "BoroName", "outSR": 4326, "f": "geojson"})
with urlopen(SOURCE + "/query?" + query, timeout=60) as response:
    boroughs = json.load(response)["features"]
# Close sub-metre gaps where independently digitized boroughs meet in the river.
# Federal islands lie across the state line. The Census water polygons join the
# two states at mid-channel and stop at the New Jersey shoreline.
CENSUS = "https://www2.census.gov/geo/tiger/TIGER2025/AREAWATER/"
waters = []
# Use both sides of the same TIGER vintage. Mixing the DCP and Census
# mid-channel lines alone leaves a narrow strip of missing water between them.
for county in ("34017", "36061", "36047", "36085", "36005"):
    base = f"tl_2025_{county}_areawater"
    with urlopen(CENSUS + base + ".zip", timeout=60) as response, zipfile.ZipFile(io.BytesIO(response.read())) as archive:
        with shapefile.Reader(shp=io.BytesIO(archive.read(base + ".shp")), dbf=io.BytesIO(archive.read(base + ".dbf"))) as reader:
            waters.extend(shape(item.shape.__geo_interface__) for item in reader.iterShapeRecords()
                          if item.record["FULLNAME"] in ("Upper New York Bay", "New York Bay", "Hudson Riv", "Greenville Reach", "Kill Van Kull"))
joined = unary_union([shape(b["geometry"]) for b in boroughs] + waters)
boundary = joined.buffer(.000001).buffer(-.000001).simplify(.000025)
origin = json.loads((ROOT / "boroughs.json").read_text())["origin"]
scale = math.pi / 180 * 6371008.8


def project(ring):
    return [[round((lon - origin["lon"]) * scale * math.cos(math.radians(origin["lat"]))),
             round((origin["lat"] - lat) * scale)] for lon, lat in list(ring.coords)[:-1]]


polygons = [boundary] if boundary.geom_type == "Polygon" else boundary.geoms
rings = [{"outer": project(p.exterior), "holes": [project(h) for h in p.interiors]} for p in polygons]
(ROOT / "harbor-limits.js").write_text("// NYC Department of City Planning · " + SOURCE + "\n// US Census Bureau · " + CENSUS + "\n"
    + "// Generated by scripts/build-harbor-limits.py\nexport const harborLimits = "
    + json.dumps(rings, separators=(",", ":")) + ";\n")
