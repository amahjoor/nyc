"""Build the outer NYC sailing boundary from DCP boroughs, including their waters.

Requires Shapely 2. The detailed dry shoreline is already in boroughs.json.
"""
import json
import math
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

from shapely.geometry import shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1] / "dist"
SOURCE = "https://services5.arcgis.com/GfwWNkhOj9bNBqoJ/arcgis/rest/services/NYC_Borough_Boundary_Water_Included/FeatureServer/0"
query = urlencode({"where": "1=1", "outFields": "BoroName", "outSR": 4326, "f": "geojson"})
with urlopen(SOURCE + "/query?" + query, timeout=60) as response:
    boroughs = json.load(response)["features"]
# Close sub-metre gaps where independently digitized boroughs meet in the river.
joined = unary_union([shape(b["geometry"]) for b in boroughs])
boundary = joined.buffer(.000001).buffer(-.000001).simplify(.000025)
origin = json.loads((ROOT / "boroughs.json").read_text())["origin"]
scale = math.pi / 180 * 6371008.8


def project(ring):
    return [[round((lon - origin["lon"]) * scale * math.cos(math.radians(origin["lat"]))),
             round((origin["lat"] - lat) * scale)] for lon, lat in list(ring.coords)[:-1]]


polygons = [boundary] if boundary.geom_type == "Polygon" else boundary.geoms
rings = [{"outer": project(p.exterior), "holes": [project(h) for h in p.interiors]} for p in polygons]
(ROOT / "harbor-limits.js").write_text("// NYC Department of City Planning · " + SOURCE + "\n"
    + "// Generated by scripts/build-harbor-limits.py\nexport const harborLimits = "
    + json.dumps(rings, separators=(",", ":")) + ";\n")
