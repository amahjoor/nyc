"""Bake FAA Airport Mapping polygons for NYC in the game's metre grid."""
import json
import math
import runpy
import struct
import zlib
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
project = runpy.run_path(str(ROOT / 'scripts/import-street-detail.py'))['project']
SOURCE = 'https://services6.arcgis.com/ssFJjBXIUyZDrSYZ/ArcGIS/rest/services/AM_'
SIZE = 2048


def features(layer):
    params = urlencode(dict(where="FAA_ID IN ('JFK','LGA')", outFields='*', orderByFields='OBJECTID', outSR=4326, f='geojson'))
    with urlopen(f'{SOURCE}{layer}/FeatureServer/0/query?{params}', timeout=45) as response:
        data = json.load(response)
    if data.get('exceededTransferLimit') or not data.get('features'):
        raise ValueError(f'Incomplete {layer} layer')
    for feature in data['features']:
        geometry = feature['geometry']
        parts = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        for part in parts:
            yield feature['properties'], [[project(*p[:2]) for p in ring[:-1]] for ring in part]


def runway_frame(ring):
    """Fit the narrowest enclosing rectangle to derive the painted strip's axis."""
    best = None
    for a, b in zip(ring, ring[1:] + ring[:1]):
        dx, dz = b[0]-a[0], b[1]-a[1]
        length = math.hypot(dx, dz)
        if length < 1:
            continue
        ux, uz = dx/length, dz/length
        along = [x*ux + z*uz for x, z in ring]
        across = [z*ux - x*uz for x, z in ring]
        span, width = max(along)-min(along), max(across)-min(across)
        if span < width:
            continue
        if best is None or span*width < best[0]:
            u, v = (min(along)+max(along))/2, (min(across)+max(across))/2
            best = span*width, [u*ux-v*uz, u*uz+v*ux, ux, uz, span/2, width/2]
    return [round(value, 6) for value in best[1]]


def fill(pixels, rings, color):
    # Scanline parity retains holes. Sample each texel at its centre.
    rows = {}
    for ring in rings:
        for (x, y), (u, v) in zip(ring, ring[1:] + ring[:1]):
            for row in range(math.ceil(min(y, v) - .5), math.ceil(max(y, v) - .5)):
                rows.setdefault(row, []).append(x + (u - x) * (row + .5 - y) / (v - y))
    for row, crossings in rows.items():
        crossings.sort()
        for left, right in zip(crossings[::2], crossings[1::2]):
            start, end = math.ceil(left - .5), math.ceil(right - .5)
            pixels[row][start:end] = bytes([color]) * (end - start)


def png_chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def build():
    layers = {layer: list(features(layer)) for layer in ('Apron', 'Taxiway', 'Runway', 'Building')}
    pixels = [bytearray(SIZE) for _ in range(SIZE)]
    airports = []
    for code, top, height in [('JFK', 0, 1344), ('LGA', 1344, 704)]:
        parts = [(layer, props, rings) for layer, values in layers.items() for props, rings in values if props['FAA_ID'] == code]
        xs, zs = zip(*(p for _, _, rings in parts for p in rings[0]))
        x, z = math.floor(min(xs)) - 10, math.floor(min(zs)) - 10
        width, depth = math.ceil(max(xs)) + 10 - x, math.ceil(max(zs)) + 10 - z
        airport = dict(code=code, rect=[x, z, width, depth], uv=[top / SIZE, height / SIZE], runways=[], buildings=[])
        for layer, props, rings in parts:
            if layer == 'Building':
                # Survey geometry supplies the volume. FAA footprints identify its use.
                airport['buildings'].append(dict(terminal='TERMINAL' in (props.get('DESIGNATOR') or ''), rings=rings))
                continue
            local = [[((px-x)*SIZE/width, top+(pz-z)*height/depth) for px, pz in ring] for ring in rings]
            fill(pixels, local, {'Runway': 1, 'Taxiway': 2, 'Apron': 3}[layer])
            if layer == 'Runway':
                airport['runways'].append(dict(name=props['RWY_ID'], rings=rings, frame=runway_frame(rings[0])))
        airports.append(airport)
        print(code, {layer: sum(k == layer for k, _, _ in parts) for layer in layers})
    header = struct.pack('>IIBBBBB', SIZE, SIZE, 8, 3, 0, 0, 0)
    image = b'\x89PNG\r\n\x1a\n' + png_chunk(b'IHDR', header)
    image += png_chunk(b'PLTE', bytes([0,0,0, 255,0,0, 0,255,0, 0,0,255]))
    image += png_chunk(b'IDAT', zlib.compress(b''.join(b'\0' + row for row in pixels), 9)) + png_chunk(b'IEND', b'')
    (ROOT / 'dist/assets/airfield-surfaces.png').write_bytes(image)
    (ROOT / 'dist/airport-data.js').write_text('// Generated by scripts/build-airports.py from FAA Airport Mapping.\nexport const airports = '
        + json.dumps(airports, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    build()
